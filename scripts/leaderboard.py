#!/usr/bin/env python3
"""Build LEADERBOARD.md — every GitHub project referenced in this repo,
ranked by total stars and by 7-day star change.

Collects github.com links from README + categories, fetches stars and
descriptions with a single GraphQL batch call (needs GITHUB_TOKEN), keeps
~35 days of snapshots in data/leaderboard-history.json, and regenerates
LEADERBOARD.md + LEADERBOARD.zh-CN.md. Runs daily in CI alongside
sync_stars.py; safe to run locally.
"""

from __future__ import annotations

import datetime as dt
import json
import os
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HISTORY = ROOT / "data" / "leaderboard-history.json"
OUT_EN = ROOT / "LEADERBOARD.md"
OUT_ZH = ROOT / "LEADERBOARD.zh-CN.md"
SELF = "vicfei/awesome-jev-prompts"
GRAPHQL = "https://api.github.com/graphql"
KEEP_DAYS = 35

# github.com path prefixes that are site sections, not owner/repo targets.
RESERVED_OWNERS = {
    "features", "topics", "sponsors", "settings", "apps", "marketplace",
    "about", "orgs", "notifications", "pulls", "issues", "explore",
    "pricing", "enterprise", "security", "site", "collections", "events",
}

LINK = re.compile(r"(?<![\w.])github\.com/([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+)")

LABELS = {
    "en": {
        "title": "# Leaderboard",
        "intro": (
            "Every GitHub project referenced in this repo — patterns' home repos, "
            "engines, skills, SDKs, benchmarks and related lists — ranked by total "
            "stars and by weekly change. Daily snapshots; the weekly change compares "
            "against the last snapshot at least 6 days old. Generated by CI "
            "(`scripts/leaderboard.py`) — do not edit by hand."
        ),
        "by_total": "## By total stars",
        "by_week": "## By weekly change",
        "no_week": (
            "No weekly data yet — tracking started {first}, deltas appear from "
            "{later}."
        ),
        "head_total": ("| # | Project | About | Stars | Δ 7d |",
                       "|---|---|---|---:|---:|"),
        "head_week": ("| # | Project | Δ 7d | Stars |", "|---|---|---:|---:|"),
        "updated": "*Updated {date}. {n} projects tracked.*",
        "unavailable": "*(unavailable)*",
    },
    "zh": {
        "title": "# 排行榜",
        "intro": (
            "本仓库收录的全部 GitHub 项目——模式出处仓库、引擎、技能、SDK、基准与相关清单——"
            "按总星数与周增量分别排序。每日快照；周增量取当前星数与最近一次至少 6 天前的快照之差。"
            "由 CI 自动生成（`scripts/leaderboard.py`），请勿手改。"
        ),
        "by_total": "## 按总星数",
        "by_week": "## 按周增量",
        "no_week": "暂无周增量数据——自 {first} 开始追踪，{later} 起可见增量。",
        "head_total": ("| # | 项目 | 简介 | 星数 | 周增量 |",
                       "|---|---|---|---:|---:|"),
        "head_week": ("| # | 项目 | 周增量 | 星数 |", "|---|---|---:|---:|"),
        "updated": "*更新于 {date}，共追踪 {n} 个项目。*",
        "unavailable": "*(暂不可用)*",
    },
}


def extract_repos(text: str) -> set[str]:
    """GitHub owner/repo targets in a markdown text, minus site sections."""
    out = set()
    for owner, repo in LINK.findall(text):
        repo = repo.rstrip(".")
        if owner.lower() in RESERVED_OWNERS or not repo:
            continue
        out.add(f"{owner}/{repo}")
    out.discard(SELF)
    return out


def collect_repos() -> list[str]:
    files = [ROOT / "README.md", ROOT / "README.zh-CN.md", *sorted((ROOT / "categories").glob("*.md"))]
    repos: set[str] = set()
    for f in files:
        repos |= extract_repos(f.read_text(encoding="utf-8"))
    return sorted(repos)


def fetch(repos: list[str]) -> dict[str, dict]:
    """One GraphQL batch call → {repo: {"stars": int, "desc": str}}."""
    token = os.environ.get("GITHUB_TOKEN")
    if not token:
        raise SystemExit("GITHUB_TOKEN not set — cannot fetch star counts")
    parts = [
        f'  r{i}: repository(owner: "{o}", name: "{n}") {{ stargazerCount description }}'
        for i, (o, n) in enumerate(r.split("/", 1) for r in repos)
    ]
    body = json.dumps({"query": "query {\n" + "\n".join(parts) + "\n}"}).encode()
    req = urllib.request.Request(
        GRAPHQL,
        data=body,
        headers={
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
            "User-Agent": "awesome-jev-prompts-leaderboard",
        },
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        data = json.load(resp)
    out: dict[str, dict] = {}
    for i, repo in enumerate(repos):
        node = (data.get("data") or {}).get(f"r{i}")
        if node is None:
            print(f"warn: {repo}: not found or inaccessible", file=sys.stderr)
            continue
        out[repo] = {"stars": node["stargazerCount"], "desc": node.get("description") or ""}
    return out


def delta7(current: int, hist: list[list], today: dt.date) -> int | None:
    """current − stars at the most recent snapshot ≥ 6 days old (else None)."""
    past = [s for d, s in hist if dt.date.fromisoformat(d) <= today - dt.timedelta(days=6)]
    return current - past[-1] if past else None


def fmt_delta(d: int | None) -> str:
    if d is None:
        return "—"
    return f"+{d:,}" if d > 0 else f"{d:,}"


def cell(text: str, cap: int = 72) -> str:
    text = " ".join(text.split())
    if len(text) > cap:
        text = text[: cap - 1].rstrip() + "…"
    return text.replace("|", "\\|") if text else "—"


def render(rows: list[dict], first_date: str | None, today: str, lang: str) -> str:
    """rows: [{repo, desc, stars, delta}] with stars possibly None."""
    L = LABELS[lang]
    lines = [
        f"<!-- generated by scripts/leaderboard.py on {today} — do not edit -->",
        "",
        L["title"],
        "",
        L["intro"],
        "",
    ]
    ranked = sorted(rows, key=lambda r: (-(r["stars"] if r["stars"] is not None else -1), r["repo"]))
    lines.append(L["by_total"])
    lines += ["", *L["head_total"]]
    for i, r in enumerate(ranked, 1):
        stars = f"{r['stars']:,}" if r["stars"] is not None else "—"
        about = cell(r["desc"]) if r["stars"] is not None else L["unavailable"]
        lines.append(f"| {i} | [{r['repo']}](https://github.com/{r['repo']}) | {about} | {stars} | {fmt_delta(r['delta'])} |")
    lines.append("")
    with_delta = [r for r in rows if r["delta"] is not None]
    lines.append(L["by_week"])
    lines.append("")
    if not with_delta:
        if first_date:
            later = (dt.date.fromisoformat(first_date) + dt.timedelta(days=7)).isoformat()
            lines.append(L["no_week"].format(first=first_date, later=later))
        lines.append("")
    else:
        lines += list(L["head_week"])
        movers = sorted(with_delta, key=lambda r: (-r["delta"], -(r["stars"] or 0), r["repo"]))
        for i, r in enumerate(movers, 1):
            stars = f"{r['stars']:,}" if r["stars"] is not None else "—"
            lines.append(f"| {i} | [{r['repo']}](https://github.com/{r['repo']}) | {fmt_delta(r['delta'])} | {stars} |")
        lines.append("")
    lines.append(L["updated"].format(date=today, n=len(rows)))
    return "\n".join(lines) + "\n"


def main() -> int:
    today = dt.date.today()
    repos = collect_repos()
    live = fetch(repos)

    hist_file: dict = json.loads(HISTORY.read_text(encoding="utf-8")) if HISTORY.exists() else {}
    first_date = min((v["hist"][0][0] for v in hist_file.values() if v.get("hist")), default=None)

    rows: list[dict] = []
    for repo in repos:
        prev = hist_file.get(repo, {})
        stars = live.get(repo, {}).get("stars", prev.get("stars"))
        desc = live.get(repo, {}).get("desc", prev.get("desc", ""))
        hist = prev.get("hist", [])
        rows.append({
            "repo": repo,
            "desc": desc,
            "stars": stars,
            "delta": delta7(stars, hist, today) if stars is not None else None,
        })
        if stars is not None:
            if hist and hist[-1][0] == today.isoformat():
                hist[-1] = [today.isoformat(), stars]
            else:
                hist.append([today.isoformat(), stars])
            hist_file[repo] = {"stars": stars, "desc": desc, "hist": hist[-KEEP_DAYS:]}

    HISTORY.parent.mkdir(exist_ok=True)
    HISTORY.write_text(json.dumps(hist_file, indent=2, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")
    OUT_EN.write_text(render(rows, first_date, today.isoformat(), "en"), encoding="utf-8")
    OUT_ZH.write_text(render(rows, first_date, today.isoformat(), "zh"), encoding="utf-8")
    print(f"leaderboard: {len(rows)} repos, {len(live)} live, wrote {OUT_EN.name} + {OUT_ZH.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
